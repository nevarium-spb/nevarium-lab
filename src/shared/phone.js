// Номер телефона — обязательное поле любой заявки на обоих сайтах и основной
// способ узнать человека: по нему CRM склеивает повторные обращения,
// учитывается бесплатная проверка (тариф Free) и подтверждаются запросы по ПДн
// (ADR-011 Визора).
//
// Общий файл: копия лежит в G:\nevarium1\src\shared\ (см. шапку
// privacy-policy.js). Править только в репозитории Визора, затем
// `npm run shared:sync`. Без импортов и без TypeScript.
//
// Поэтому в CRM уходит не то, что человек напечатал, а один канонический вид
// (+7XXXXXXXXXX для России, E.164 для остальных): «8 (921) 555-14-88» и
// «+7 921 5551488» должны оказаться одним и тем же номером, а не двумя людьми.

/**
 * @param {string} raw — ввод человека.
 * @returns {string|null} номер в виде +<цифры> или null, если это не телефон.
 */
export function normalizePhone(raw) {
  const s = String(raw ?? '').trim()
  // Только цифры и привычные разделители; буквы и «@» — не телефон.
  if (!/^\+?[\d\s().-]+$/.test(s)) return null
  const d = s.replace(/\D/g, '')

  if (s.startsWith('+')) {
    // +7 — Россия и Казахстан: ровно 11 цифр, иначе это опечатка, а не номер.
    if (d.startsWith('7')) return d.length === 11 ? `+${d}` : null
    // Остальные страны — по E.164: не длиннее 15 цифр.
    return d.length >= 8 && d.length <= 15 ? `+${d}` : null
  }
  // Российские номера без «+»: 8XXXXXXXXXX и 7XXXXXXXXXX.
  if (d.length === 11 && (d[0] === '8' || d[0] === '7')) return `+7${d.slice(1)}`
  // Без кода страны: 10 цифр, коды российских сетей начинаются на 3, 4, 8 или 9.
  if (d.length === 10 && /^[3489]/.test(d)) return `+7${d}`
  return null
}
